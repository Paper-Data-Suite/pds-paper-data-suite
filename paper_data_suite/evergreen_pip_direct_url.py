"""Issue #49: strict, read-only provenance for pip local-wheel direct_url.json.

PEP 610 metadata is generated by pip and NOT a signature. This checks the
record against an independently authenticated wheelhouse pin. Do not accept
remote URLs, user-selected local files, VCS, or editable source locations.
"""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path
from typing import Final, cast

_MAX_BYTES: Final = 4096
_SHA: Final = re.compile(r"[0-9a-f]{64}\Z")


class PipDirectUrlError(ValueError):
    """Local pip wheel provenance is malformed or differs from the signed lock."""


def _unique(pairs: list[tuple[str, object]]) -> dict[str, object]:
    output: dict[str, object] = {}
    for key, value in pairs:
        if key in output:
            raise PipDirectUrlError("duplicate pip direct URL JSON field")
        output[key] = value
    return output


def inspect_locked_pip_direct_url(
    raw: bytes, *, wheel_path: Path, wheel_sha256: str
) -> tuple[str, int]:
    """Verify pip's local-wheel origin and hashes; return metadata byte identity.

    No URL is followed and no wheel is acquired; `wheel_path` and digest MUST
    originate from an already verified signed wheelhouse, never this document.
    """
    if (
        type(raw) is not bytes
        or not 1 <= len(raw) <= _MAX_BYTES
        or not isinstance(wheel_path, Path)
        or type(wheel_sha256) is not str
        or not _SHA.fullmatch(wheel_sha256)
    ):
        raise PipDirectUrlError("invalid pip direct URL verification inputs")
    try:
        data: object = json.loads(raw.decode("utf-8"), object_pairs_hook=_unique)
    except PipDirectUrlError:
        raise
    except (UnicodeDecodeError, ValueError, RecursionError) as error:
        raise PipDirectUrlError("malformed pip direct URL JSON") from error
    if not isinstance(data, dict):
        raise PipDirectUrlError("pip direct URL must be an object")
    document = cast(dict[str, object], data)
    if document.keys() != {"url", "archive_info"}:
        raise PipDirectUrlError("unsupported pip direct URL origin")
    # urllib path normalization is deliberately not performed: signed wheel
    # filename and canonical wheelhouse path must be an exact local match.
    if document["url"] != wheel_path.absolute().as_uri():
        raise PipDirectUrlError("pip direct URL does not identify locked wheel")
    archive = document["archive_info"]
    if not isinstance(archive, dict):
        raise PipDirectUrlError("invalid pip direct URL archive provenance")
    info = cast(dict[str, object], archive)
    if info.keys() != {"hash", "hashes"}:
        raise PipDirectUrlError("unsupported pip direct URL hash fields")
    if info["hash"] != f"sha256={wheel_sha256}" or info["hashes"] != {
        "sha256": wheel_sha256
    }:
        raise PipDirectUrlError("pip direct URL digest differs from signed lock")
    return hashlib.sha256(raw).hexdigest(), len(raw)


__all__ = ("PipDirectUrlError", "inspect_locked_pip_direct_url")
